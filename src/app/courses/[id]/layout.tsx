// @modal объявлен здесь, не в корневом layout.tsx — намеренно: перехватчик внутри
// него ((..)lessons/[id]) должен реагировать ТОЛЬКО на клик, сделанный откуда-то из-под
// /courses/[id] (например, со страницы курса), не откуда угодно в приложении. Слот активен,
// только пока в дереве рендерится этот layout — переход по <Link> к /lessons/[id] с самой
// полной страницы урока (кнопки "предыдущий/следующий урок") идёт мимо /courses/[id]
// вообще, поэтому там @modal не участвует и срабатывает обычная, полная навигация.
export default function CourseLayout({ children, modal }: LayoutProps<"/courses/[id]">) {
  return (
    <>
      {children}
      {modal}
    </>
  );
}
